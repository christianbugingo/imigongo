/// Rotation-normalized topology identity; palette and scramble are excluded.
String topologyKey(Board board) {
  var masks = [for (final tile in board.tiles) tile.targetMask];
  final keys = <String>[];
  for (var turn = 0; turn < 4; turn++) {
    keys.add(
      '${board.size}:${masks.map((m) => m.toString().padLeft(2, '0')).join(',')}',
    );
    final rotated = List<int>.filled(masks.length, 0);
    for (var r = 0; r < board.size; r++) {
      for (var c = 0; c < board.size; c++) {
        rotated[c * board.size + board.size - 1 - r] =
            ConnectionMask.rotateClockwise(masks[r * board.size + c], 1);
      }
    }
    masks = rotated;
  }
  keys.sort();
  return keys.first;
}

List<ChallengeLevel> buildCatalog() {
  const legacy = <String, (int, int)>{
    'easy-1': (3, 42),
    'easy-2': (3, 2),
    'easy-3': (4, 71),
    'medium-1': (4, 2),
    'medium-2': (4, 421),
    'medium-3': (5, 119),
    'hard-1': (5, 603),
    'hard-2': (6, 57),
    'hard-3': (7, 808),
  };
  const palettes = ['classic', 'clay', 'ochre', 'mixed', 'inverse'];
  final seen = <String>{};
  final result = <ChallengeLevel>[];
  var number = 1;
  for (final tier in ChallengeTier.values) {
    final count = tier == ChallengeTier.medium ? 20 : 15;
    var candidateSeed = 26000 + tier.index * 10000;
    for (var index = 1; index <= count; index++, number++) {
      final id = '${tier.name}-$index';
      final saved = legacy[id];
      final nextId = index < count
          ? '${tier.name}-${index + 1}'
          : tier == ChallengeTier.hard
          ? null
          : '${ChallengeTier.values[tier.index + 1].name}-1';
      final palette = palettes[(number - 1) % palettes.length];
      if (saved != null) {
        final level = ChallengeLevel(
          id,
          number,
          saved.$1,
          saved.$2,
          tier,
          nextId,
          paletteId: palette,
        );
        if (!seen.add(topologyKey(level.generate()))) {
          throw StateError('Duplicate legacy topology');
        }
        result.add(level);
        continue;
      }
      final size = switch (tier) {
        ChallengeTier.easy => index <= 6 ? 3 : 4,
        ChallengeTier.medium => index <= 10 ? 4 : 5,
        ChallengeTier.hard => 7,
      };
      Board? chosen;
      for (var attempt = 0; attempt < 50000; attempt++) {
        final board = CenterNetworkGenerator.generate(
          size: size,
          seed: candidateSeed++,
        );
        final rotatable = board.tiles
            .where(
              (t) =>
                  ConnectionMask.rotateClockwise(t.baseMask, 1) != t.baseMask,
            )
            .length;
        final minPar = tier == ChallengeTier.hard
            ? 30
            : tier == ChallengeTier.medium
            ? 12
            : 4;
        if (board.par < minPar ||
            (tier == ChallengeTier.hard && rotatable < 22)) {
          continue;
        }
        if (seen.add(topologyKey(board))) {
          chosen = board;
          break;
        }
      }
      if (chosen == null) {
        throw StateError('Could not find distinct content for $id');
      }
      result.add(
        ChallengeLevel(
          id,
          number,
          chosen.size,
          chosen.seed,
          tier,
          nextId,
          generatorVersion: 3,
          paletteId: palette,
        ),
      );
    }
  }
  return result;
}

void main(List<String> args) {
  final levels = buildCatalog();
  if (args.contains('--write')) {
    final source = StringBuffer(
      "// Generated by tool/build_50_levels.dart. Do not edit.\npart of 'challenge_catalog.dart';\n\nconst _challengeLevels = <ChallengeLevel>[\n",
    );
    for (final l in levels) {
      source.writeln(
        "  ChallengeLevel('${l.id}', ${l.number}, ${l.size}, ${l.seed}, ChallengeTier.${l.tier.name}, ${l.nextId == null ? 'null' : "'${l.nextId}'"}, generatorVersion: ${l.generatorVersion}, paletteId: '${l.paletteId}'),",
      );
    }
    source.writeln('];');
    File('lib/engine/content/challenge_levels.g.dart')
        .writeAsStringSync(source.toString());
  }
  print(
    const JsonEncoder.withIndent('  ').convert({
      'levelCount': levels.length,
      'uniqueTopologies': levels
          .map((l) => topologyKey(l.generate()))
          .toSet()
          .length,
      'levels': [
        for (final l in levels)
          {
            'id': l.id,
            'number': l.number,
            'tier': l.tier.name,
            'size': l.size,
            'seed': l.seed,
            'generatorVersion': l.generatorVersion,
            'palette': l.paletteId,
            'par': l.generate().par,
            'nextId': l.nextId,
          },
      ],
    }),
  );
}
